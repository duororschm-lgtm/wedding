create or replace function public.garden_count()
returns bigint
language sql
security definer
set search_path = public
as $$ select count(*) from public.garden $$;

grant execute on function public.garden_count() to anon, authenticated;

-- ============================================================
-- ⑦ 云存储桶（照片 / 音乐，公开可读，登录者可上传删除）
-- ============================================================
insert into storage.buckets (id, name, public)
values ('photos', 'photos', true), ('music', 'music', true)
on conflict (id) do nothing;

create policy "图片音乐公开可读" on storage.objects
  for select using (bucket_id in ('photos', 'music'));
create policy "管理员可上传" on storage.objects
  for insert to authenticated with check (bucket_id in ('photos', 'music'));
create policy "管理员可删除" on storage.objects
  for delete to authenticated using (bucket_id in ('photos', 'music'));
